"""Generate exact, immutable timing inputs before any device timing begins."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import struct

ROOT = Path(__file__).resolve().parents[1]


def bits(value):
    return struct.unpack('<Q', struct.pack('<d', value))[0]


def number(value):
    return struct.unpack('<d', struct.pack('<Q', value))[0]


def generate():
    rng = random.Random(20261029)
    domains = {k: [] for k in ['positive', 'near_one', 'magnitude',
                              'negative_integer', 'subnormal', 'range_edge', 'special']}
    special = [0., -0., 1., -1., 2., -2., math.inf, -math.inf,
               math.nan, number(0x7ff0000000000001), number(1), number(0x10000000000000)]
    for i in range(64):
        u, v = rng.random(), rng.random()
        domains['positive'].append((.5 + 1.5 * u, -8 + 16 * v))
        domains['near_one'].append((1 + (u - .5) * 2e-8, (v - .5) * 2e10))
        exponent = rng.randrange(-1000, 1001)
        domains['magnitude'].append((math.ldexp(.5 + u, exponent), (v - .5) * 100 / max(1, abs(exponent))))
        domains['negative_integer'].append((-.5 - 1.5 * u, float(rng.randrange(-16, 17))))
        domains['subnormal'].append((number(rng.randrange(1, 1 << 52)), .2 + 1.3 * v))
        domains['range_edge'].append((2 + (u - .5) * 1e-12, (1024. if i % 2 else -1075.) + (v - .5) * 1e-9))
        domains['special'].append((special[i % len(special)], special[(i // len(special) + i) % len(special)]))
    lines = ['// Generated by scripts/generate_vectors.py; integer bits avoid target-dependent parsing.',
             '/// Independently measured distributions with offsets into the immutable table.',
             'pub const DOMAINS: [Domain; 7] = [']
    for i, name in enumerate(domains):
        lines.append(f'    Domain {{ name: "{name}", start: {i * 64}, count: 64, special: {str(name == "special").lower()} }},')
    lines += ['];', '#[rustfmt::skip]', 'static DATA: [Case; 448] = [']
    raw = bytearray()
    for pairs in domains.values():
        for x, y in pairs:
            xb, yb = bits(x), bits(y)
            lines.append(f'    Case {{ x: 0x{xb:016x}, y: 0x{yb:016x} }},')
            raw.extend(struct.pack('<QQ', xb, yb))
    lines.append('];')
    # Keep both generated declarations stable under rustfmt.
    lines.insert(1, '#[rustfmt::skip]')
    return '\n'.join(lines) + '\n', bytes(raw)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, raw = generate()
    outputs = {
        ROOT / 'core/src/vectors/data.rs': source.encode(),
        ROOT / 'vectors/timing.bin': raw,
        ROOT / 'vectors/timing.sha256': (hashlib.sha256(raw).hexdigest() + '\n').encode(),
        ROOT / 'vectors/manifest.json': (json.dumps({
            'seed': 20261029, 'cases': 448, 'encoding': 'little-endian pairs of u64 binary64 bits',
            'sha256': hashlib.sha256(raw).hexdigest(),
        }, indent=2) + '\n').encode(),
    }
    for path, content in outputs.items():
        if args.check:
            if path.read_bytes() != content:
                raise ValueError(f'generated vectors differ: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)


if __name__ == '__main__':
    main()
